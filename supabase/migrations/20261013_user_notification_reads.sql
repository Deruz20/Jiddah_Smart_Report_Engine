-- Date: 2026-10-13
-- Author: Jiddah Engine Architecture Team
-- Description: Enables independent, per-user read tracking for broadcast notifications
-- Status: PREPARED (DO NOT APPLY AUTOMATICALLY TO PRODUCTION SUPABASE)
-- Rehearsed in a disposable local PostgreSQL 17 (Supabase CLI) against a representative
-- baseline where public.notifications.id is INTEGER. Local SQL/RLS checks only; not an
-- authenticated browser E2E test and not applied to any remote environment.
--
-- Re-run behavior: the policy statements are safe to re-run (DROP POLICY IF EXISTS before each
-- CREATE POLICY), and re-running was verified to leave policies and grants unchanged.
-- Limitation: CREATE TABLE / CREATE INDEX IF NOT EXISTS only skip when the object already exists.
-- They do NOT repair a pre-existing table or index whose definition differs (for example a
-- notification_id of a different type). This migration does not repair schema drift.
--
-- Prerequisite: public.notifications.id must be INTEGER. If production differs, notification_id
-- must be changed to match before applying.

-- Up Migration
CREATE TABLE IF NOT EXISTS public.notification_reads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id INTEGER NOT NULL REFERENCES public.notifications(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  read_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_user_notification_read UNIQUE(notification_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_notification_reads_user_id ON public.notification_reads(user_id);
CREATE INDEX IF NOT EXISTS idx_notification_reads_notification_id ON public.notification_reads(notification_id);

ALTER TABLE public.notification_reads ENABLE ROW LEVEL SECURITY;

-- Least-privilege table access. Supabase default privileges otherwise grant anon and
-- authenticated full table privileges on new public tables. Rows are still limited by RLS.
-- Identity inserts did not require sequence USAGE in the rehearsal, so none is granted here.
REVOKE ALL ON TABLE public.notification_reads FROM anon;
REVOKE ALL ON TABLE public.notification_reads FROM authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.notification_reads TO authenticated;

DROP POLICY IF EXISTS "Users can view their own notification read status" ON public.notification_reads;
CREATE POLICY "Users can view their own notification read status"
  ON public.notification_reads
  FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own notification read status" ON public.notification_reads;
CREATE POLICY "Users can insert their own notification read status"
  ON public.notification_reads
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own notification read status" ON public.notification_reads;
CREATE POLICY "Users can update their own notification read status"
  ON public.notification_reads
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id);

-- Rollback (NOT part of this migration; manual and DESTRUCTIVE)
-- Dropping public.notification_reads permanently deletes every persisted per-user broadcast
-- read timestamp. There is no automatic down migration. If a rollback is ever required, it must
-- be a deliberate, separately reviewed operation, for example:
--   DROP TABLE public.notification_reads;
-- The application falls back to activity_logs when the table is absent, but reads recorded only
-- in notification_reads would be lost.
